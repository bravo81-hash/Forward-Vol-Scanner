def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    try:
        raw = base64.b64decode(PAYLOAD)
    except Exception as exc:
        print("payload did not decode: %s" % exc, file=sys.stderr)
        print("The paste was truncated or altered. Re-copy the whole file.",
              file=sys.stderr)
        return 1

    got = hashlib.sha256(raw).hexdigest()
    if got != SHA256:
        print("CHECKSUM MISMATCH - the paste is incomplete or altered.",
              file=sys.stderr)
        print("  expected %s" % SHA256, file=sys.stderr)
        print("  got      %s" % got, file=sys.stderr)
        return 1
    print("payload verified (%d bytes)" % len(raw))

    if not Path("webapp.py").exists() or not Path("selection").is_dir():
        print("Run this from the repo root (webapp.py not found).", file=sys.stderr)
        return 1

    if args.check:
        print("--check: nothing written. Files that would be installed:")
        for f in FILES:
            print("    %s" % f)
        return 0

    for d in ("core", "selection", "strategies", "static", "tests", "docs"):
        Path(d).mkdir(exist_ok=True)

    backup = Path(".equity_backup")
    backup.mkdir(exist_ok=True)
    for f in FILES:
        p = Path(f)
        if p.exists():
            shutil.copy2(p, backup / f.replace("/", "__"))

    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as tar:
        for m in tar.getmembers():
            if m.name not in FILES or not m.isfile():
                print("  refusing unexpected member: %s" % m.name, file=sys.stderr)
                return 1
        try:
            tar.extractall(".", filter="data")
        except TypeError:                       # Python < 3.12
            tar.extractall(".")

    for f in FILES:
        print("  wrote: %s" % f)
    print("")
    print("%d files installed. Replaced originals are in %s/" % (len(FILES), backup))
    print("Next: python -m pytest tests/test_equity_leaps.py -q   (expect 59 passed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())